"""Portable source training, few-shot adaptation, and final-checkpoint evaluation."""
from __future__ import annotations
import os
os.environ.setdefault('CUBLAS_WORKSPACE_CONFIG', ':4096:8')
import json
import random
import time
from pathlib import Path
import numpy as np
import torch
from torch.utils.data import DataLoader
from .model import GIFT
from .data import datasets, file_sha256
from .metrics import MetricAccumulator


def write_json(path, obj):
    path = Path(path); path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + '.tmp')
    tmp.write_text(json.dumps(obj, indent=2, allow_nan=False))
    tmp.replace(path)


def seed_all(seed, threads=2):
    random.seed(seed); np.random.seed(seed); torch.manual_seed(seed)
    if torch.cuda.is_available(): torch.cuda.manual_seed_all(seed)
    torch.set_num_threads(threads)
    torch.use_deterministic_algorithms(True)
    torch.backends.cudnn.benchmark = False
    torch.backends.cudnn.deterministic = True
    torch.backends.cuda.matmul.allow_tf32 = False
    torch.backends.cudnn.allow_tf32 = False


def rng_state():
    return dict(python=random.getstate(), numpy=np.random.get_state(), torch=torch.get_rng_state(),
                cuda=torch.cuda.get_rng_state_all() if torch.cuda.is_available() else [])


def restore_rng(state):
    random.setstate(state['python']); np.random.set_state(state['numpy']); torch.set_rng_state(state['torch'])
    if torch.cuda.is_available() and state['cuda']: torch.cuda.set_rng_state_all(state['cuda'])


def make_model(config, seed, device):
    spec = config['model']
    if spec['history_length'] != 12 or spec['dropout'] != .1:
        raise ValueError('This release preserves history length 12 and dropout 0.1; other values require an explicit model change')
    return GIFT(horizon=config['horizon'], seed=seed, width=spec['width'],
                rank=spec['rank'], blocks=spec['blocks'], ffn_width=spec['ffn_width'],
                dropout=spec['dropout']).to(device)


def batch_payload(dataset, indices, device):
    rows = [dataset[int(i)] for i in indices]
    return tuple(torch.stack([row[k] for row in rows]).to(device) for k in range(3))


def train(config, seed, stage, data_root, output, device='cuda', source_checkpoint=None,
          epochs=None, max_updates=None, threads=2):
    output = Path(output); output.mkdir(parents=True, exist_ok=True)
    source = stage == 'pretrain'
    if not source and not source_checkpoint:
        raise ValueError('Adaptation requires the source checkpoint generated by pretraining')
    final_path = output / ('source.pt' if source else 'adapted.pt')
    if final_path.exists():
        raise FileExistsError(f'Checkpoint already exists: {final_path}; choose another output directory')
    seed_all(seed, threads)
    training, _, _, identity = datasets(config, data_root, stage)
    if training is None:
        raise ValueError('Training requires a nonempty support interval')
    m = make_model(config, seed, device)
    if source:
        seed_all(seed + 50000, threads)
    else:
        parent = torch.load(source_checkpoint, map_location='cpu', weights_only=False)
        for key in ('source', 'target', 'horizon', 'model'):
            if parent['config'][key] != config[key]:
                raise ValueError('Source checkpoint configuration differs: ' + key)
        if parent['seed'] != seed: raise ValueError('Source checkpoint seed differs')
        short_parent = not parent.get('formal_budget_complete')
        if short_parent and epochs is None and max_updates is None:
            raise ValueError('A formal adaptation requires a complete source checkpoint; use an explicit diagnostic budget to adapt a short run')
        m.load_state_dict(parent['model'], strict=True)
        m.freeze_communication()
        restore_rng(parent['rng'])
    spec = config['source_training'] if source else config['adaptation']
    epochs = spec['epochs'] if epochs is None else epochs
    batch_size = spec['batch_size']
    epoch_steps = len(training) // batch_size
    if epoch_steps == 0 or epochs <= 0: raise ValueError('Not enough windows for one training batch')
    prescribed = spec['epochs'] * epoch_steps
    if prescribed != config['source_updates' if source else 'target_updates']:
        raise ValueError('Dataset windows do not reproduce the configured formal update budget')
    budget = epochs * epoch_steps
    if max_updates is not None:
        if max_updates < 1: raise ValueError('max_updates must be positive')
        budget = min(budget, max_updates)
    formal = epochs == spec['epochs'] and budget == prescribed and (source or not short_parent)
    params = [p for p in m.parameters() if p.requires_grad]
    optimizer = torch.optim.AdamW(params, lr=spec['learning_rate'], weight_decay=spec['weight_decay'])
    generator = torch.Generator().manual_seed(seed + (0 if source else 10000))
    # Precompute the audited index-only DataLoader draws. This uses an independent
    # generator and includes the DataLoader iterator-base seed and sampler draws.
    plans = []
    for _ in range(epochs):
        loader = DataLoader(torch.arange(len(training)), batch_size=batch_size, shuffle=True,
                            drop_last=True, num_workers=0, generator=generator)
        plans.append(np.stack([indices.numpy() for indices in loader]).astype(np.int32))
    plans = np.concatenate(plans)[:budget]
    frozen = {n: p.detach().cpu().clone() for n, p in m.named_parameters() if not p.requires_grad}
    m.train(); started = time.monotonic(); losses = []; completed = 0
    write_json(output / 'parameter_audit.json', m.parameter_audit())
    for indices in plans:
        x, y, valid_history = batch_payload(training, indices, device)
        m.history_valid_mask = valid_history
        optimizer.zero_grad(set_to_none=True)
        prediction = m(x)
        # The formal forecast loss is unmasked L1 in dataset-normalized coordinates.
        loss = torch.nn.functional.l1_loss(prediction, y)
        loss = loss + config['history_auxiliary_weight'] * m.auxiliary_loss(valid_history)
        if not torch.isfinite(loss): raise RuntimeError('Nonfinite training loss')
        loss.backward()
        norm = torch.nn.utils.clip_grad_norm_(params, spec['grad_clip'])
        if not torch.isfinite(norm): raise RuntimeError('Nonfinite gradient')
        optimizer.step(); completed += 1; losses.append(float(loss.detach()))
        if completed % epoch_steps == 0 or completed == budget:
            row = dict(updates=completed, epoch=completed / epoch_steps, mean_loss=float(np.mean(losses)),
                       elapsed_seconds=time.monotonic() - started)
            print(json.dumps(row), flush=True); losses = []
            with (output / 'training.jsonl').open('a') as f: f.write(json.dumps(row) + '\n')
    assert all(torch.equal(frozen[n], p.detach().cpu()) for n, p in m.named_parameters() if n in frozen)
    payload = dict(model={k: v.detach().cpu() for k, v in m.state_dict().items()}, config=config, seed=seed,
                   stage=stage, rng=rng_state(), dataset_stats=[training.mean, training.std],
                   completed_updates=completed, formal_budget_complete=formal, data_identity=identity)
    temp = final_path.with_suffix('.tmp'); torch.save(payload, temp); temp.replace(final_path)
    result = dict(stage=stage, seed=seed, completed_updates=completed,
                  prescribed_updates=prescribed, formal_budget_complete=formal, checkpoint_sha256=file_sha256(final_path),
                  parameter_audit=m.parameter_audit(), data_identity=identity)
    if not source:
        result['metrics'] = evaluate(config, seed, final_path, data_root, device, threads=threads)
    write_json(output / ('source_result.json' if source else 'adapted_result.json'), result)
    return result


@torch.no_grad()
def evaluate(config, seed, checkpoint, data_root, device='cuda', threads=2, save_predictions=None):
    seed_all(seed, threads)
    state = torch.load(checkpoint, map_location='cpu', weights_only=False)
    if state['seed'] != seed: raise ValueError('Checkpoint seed differs')
    for key in ('source', 'target', 'horizon', 'model'):
        if state['config'][key] != config[key]: raise ValueError('Checkpoint configuration differs: ' + key)
    _, inputs, canonical, identity = datasets(config, data_root, 'adapt', source_stats=state['dataset_stats'])
    m = make_model(config, seed, device)
    m.load_state_dict(state['model'], strict=True); m.eval()
    acc = MetricAccumulator(config['horizon'])
    predictions = None
    if save_predictions:
        path = Path(save_predictions); path.parent.mkdir(parents=True, exist_ok=True)
        predictions = np.lib.format.open_memmap(path, mode='w+', dtype=np.float32,
                                                shape=(len(inputs), inputs.city.speed.shape[1], config['horizon']))
        np.save(path.with_name(path.stem + '_window_indices.npy'), inputs.starts)
    for start in range(0, len(inputs), 16):
        indices = np.arange(start, min(start + 16, len(inputs)))
        x, _, valid_history = batch_payload(inputs, indices, device)
        m.history_valid_mask = valid_history
        prediction = (m(x).cpu().numpy() * inputs.std + inputs.mean).astype(np.float32)
        truth = np.stack([canonical[int(i)][1].numpy() for i in indices])
        truth = (truth * canonical.std + canonical.mean).astype(np.float32)
        acc.update(prediction, truth)
        if predictions is not None: predictions[start:start + len(indices)] = prediction
    if predictions is not None: predictions.flush()
    value = acc.result()
    value['reported_minutes'] = [s * inputs.city.interval_minutes for s in value['reported_steps']]
    value['data_identity'] = identity
    value['checkpoint_stage'] = state['stage']
    value['formal_budget_complete'] = state['formal_budget_complete']
    return value
